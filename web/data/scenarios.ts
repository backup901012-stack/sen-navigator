// SEN 教養實務「情境應對訓練」題庫
// ──────────────────────────────────────────────────────────────
// 出發點：由 SEN 父母角度，面對孩子在真實生活場景中的情緒／感官需要，
//         練習「點回應先幫到孩子」。每條情境沒有單一標準答案，
//         而是按以下實證框架，把回應分為「好回應 / 要小心 / 應避免」三層，
//         並解釋背後原理，最後串聯「面對途人說教與投訴」的壓力應對。
//
// 內容依據（實證框架，非個人意見）：
//  1. 崩潰 ≠ 扭計（Meltdown vs Tantrum）：崩潰是神經系統超載的反應、非目標導向、
//     當事人無法即時自控；扭計多為目標導向的溝通。處理方向完全不同。
//     來源：Autism Parenting Magazine、ABA 臨床整理。
//  2. 共同調節（Co-regulation）+ 低喚醒法（Low-arousal）：先穩住自己情緒，
//     減少感官刺激，確保安全，崩潰當下「先安全、後教導」。來源：A. McDonnell 低喚醒法整理。
//  3. 感官調節（Sensory regulation）：尋求型行為多是孩子自我調節未被滿足的感官需要，
//     提供「安全的替代輸入」（深壓、擠捏）比一味制止有效。來源：職業治療 SPD 整理。
//  4. 情緒教練五步（Gottman Emotion Coaching）：① 覺察情緒 ② 視為連結／教導機會
//     ③ 協助孩子為情緒命名 ④ 表達同理理解 ⑤ 設限並一齊解難。
//  5. 香港在地（協康會）：用視覺提示讓孩子明白環境期望、以舒緩活動平衡高漲情緒、
//     家長先學行為處理知識。來源：協康會青蔥計劃 / 家長資源中心。
//  6. 同理 ≠ 同情（Brené Brown）：與孩子／家庭平等同在、不評價、不憐憫。
//
// ⚠️ 重要：本題庫為教養「練習與心理支援」，不是診斷或治療指引；
//          每個孩子不同，個別處理請諮詢職業治療師／臨床心理學家／協康會等專業。

export interface ScenarioOption {
  /** 唯一 id（場景內） */
  id: string;
  /** 父母可揀的回應 */
  text: string;
  /** 三層評價 */
  tier: "good" | "caution" | "avoid";
  /** 點解好／要小心／應避免（附原理） */
  feedback: string;
}

export interface Scenario {
  id: string;
  /** 孩子化名 + 年齡 */
  child: string;
  /** 場景（地鐵 / 超市…） */
  setting: string;
  /** 行為性質標籤 */
  nature: string;
  /** 詳細情境 */
  situation: string;
  /** 提問 */
  prompt: string;
  options: ScenarioOption[];
  /** 核心原則（一句記住） */
  takeaway: string;
}

